"use client";

import { useState } from "react";
import { useQueryClient } from "@tanstack/react-query";
import { Copy, KeyRound, ShieldCheck, Smartphone } from "lucide-react";
import { Button } from "@/components/ui/Button";
import { Field, Input } from "@/components/ui/Form";
import { useToast } from "@/components/Providers";
import { api, ApiError } from "@/lib/api";
import { keys } from "@/lib/queries";

type Setup = { secret: string; otpauthUrl: string; qrDataUrl: string };

/**
 * Admin two-factor gate (D-24). Admins must enroll an authenticator app once, then confirm a 6-digit code at the start
 * of every admin session. The API enforces this on every admin endpoint; this component only provides the UI.
 */
export function AdminMfaGate({ enrolled }: { enrolled: boolean }) {
  const qc = useQueryClient();
  const toast = useToast();
  const [setup, setSetup] = useState<Setup | null>(null);
  const [code, setCode] = useState("");
  const [error, setError] = useState<string | undefined>();
  const [busy, setBusy] = useState(false);

  async function start() {
    setBusy(true);
    setError(undefined);
    try {
      setSetup(await api<Setup>("/organizer/auth/mfa/setup", { method: "POST" }));
    } catch (e) {
      toast("error", e instanceof ApiError ? e.message : "Couldn't start setup.");
    } finally {
      setBusy(false);
    }
  }

  async function submit(e: React.FormEvent) {
    e.preventDefault();
    setBusy(true);
    setError(undefined);
    try {
      await api(`/organizer/auth/mfa/${enrolled ? "verify" : "enable"}`, { method: "POST", body: { code: code.replace(/\s/g, "") } });
      if (!enrolled) toast("success", "Two-factor authentication is on.");
      await qc.invalidateQueries({ queryKey: keys.organizer });
      await qc.invalidateQueries();
    } catch (err) {
      setError(err instanceof ApiError ? (err.fieldError("code") ?? err.message) : "Something went wrong. Try again.");
      setCode("");
    } finally {
      setBusy(false);
    }
  }

  const codeForm = (
    <form onSubmit={submit} className="space-y-4">
      <Field label="6-digit code" htmlFor="mfa-code" error={error}>
        <Input id="mfa-code" value={code} onChange={(e) => setCode(e.target.value.replace(/[^\d\s]/g, "").slice(0, 7))}
          inputMode="numeric" autoComplete="one-time-code" placeholder="123456" autoFocus aria-invalid={!!error} className="font-mono text-lg tracking-[0.3em]" />
      </Field>
      <Button type="submit" className="w-full" loading={busy} disabled={code.replace(/\s/g, "").length !== 6}>
        {enrolled ? "Verify" : "Turn on two-factor"}
      </Button>
    </form>
  );

  return (
    <div className="mx-auto max-w-md py-6">
      <div className="card space-y-5 p-6">
        <div className="flex items-center gap-3">
          <span className="grid size-11 place-items-center rounded-2xl bg-primary/15 text-accent-light"><ShieldCheck className="size-6" /></span>
          <div>
            <h1 className="font-display text-xl font-semibold">{enrolled ? "Confirm it's you" : "Secure the admin panel"}</h1>
            <p className="text-sm text-text-2">{enrolled ? "Enter the code from your authenticator app." : "Admins must use two-factor authentication."}</p>
          </div>
        </div>

        {enrolled ? codeForm : !setup ? (
          <>
            <ol className="space-y-3 text-sm text-text-2">
              <li className="flex gap-3"><Smartphone className="mt-0.5 size-4 shrink-0 text-accent-light" />Install an authenticator app such as Google Authenticator, Microsoft Authenticator, 1Password or Authy.</li>
              <li className="flex gap-3"><KeyRound className="mt-0.5 size-4 shrink-0 text-accent-light" />Scan the QR code we show you, then enter the 6-digit code it displays.</li>
            </ol>
            <Button className="w-full" onClick={start} loading={busy}>Set up authenticator</Button>
          </>
        ) : (
          <>
            {/* eslint-disable-next-line @next/next/no-img-element -- data URL generated by the API */}
            <img src={setup.qrDataUrl} alt="Authenticator setup QR code" width={200} height={200} className="mx-auto rounded-xl bg-white p-2" />
            <div className="space-y-1.5">
              <p className="text-xs text-text-2">Can&apos;t scan? Enter this key manually:</p>
              <div className="flex items-center gap-2 rounded-xl bg-bg-2 px-3 py-2">
                <code className="flex-1 font-mono text-sm break-all">{setup.secret.match(/.{1,4}/g)?.join(" ")}</code>
                <button type="button" aria-label="Copy key" className="rounded-lg p-1.5 text-text-2 hover:bg-white/5 hover:text-text"
                  onClick={() => navigator.clipboard?.writeText(setup.secret).then(() => toast("success", "Key copied"), () => {})}><Copy className="size-4" /></button>
              </div>
            </div>
            {codeForm}
          </>
        )}
        <p className="text-xs text-text-2">Lost your authenticator? Recover your organizer account with your recovery code — this resets two-factor so you can set it up again.</p>
      </div>
    </div>
  );
}
